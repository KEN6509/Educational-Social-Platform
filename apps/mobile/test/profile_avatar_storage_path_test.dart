import 'package:cyanzone_mobile/src/features/profile/data/profile_avatar_storage_path.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:supabase_flutter/supabase_flutter.dart';

void main() {
  const userId = 'user-1';
  const legacyUrl =
      'https://project.supabase.co/storage/v1/object/public/avatars/user-1/avatar.jpg';

  test('each avatar replacement uses a new storage path', () {
    final first = profileAvatarStoragePath('user-1', uploadId: 'upload-1');
    final replacement =
        profileAvatarStoragePath('user-1', uploadId: 'upload-2');

    expect(first, 'user-1/avatar-upload-1.jpg');
    expect(replacement, 'user-1/avatar-upload-2.jpg');
    expect(replacement, isNot(first));
  });

  test('extracts the previous avatar only from the current user bucket', () {
    expect(
      ownedProfileAvatarStoragePath(
        avatarUrl: legacyUrl,
        userId: userId,
        expectedLegacyUrl: legacyUrl,
      ),
      'user-1/avatar.jpg',
    );
    expect(
      ownedProfileAvatarStoragePath(
        avatarUrl:
            'https://project.supabase.co/storage/v1/object/public/avatars/user-1/avatar-123.jpg',
        userId: userId,
        expectedLegacyUrl: legacyUrl,
      ),
      'user-1/avatar-123.jpg',
    );
  });

  test('does not select external or other-user images for deletion', () {
    for (final url in [
      'https://elsewhere.example/storage/v1/object/public/avatars/user-1/avatar.jpg',
      'https://project.supabase.co/storage/v1/object/public/avatars/user-2/avatar.jpg',
      'https://project.supabase.co/storage/v1/object/public/images/user-1/avatar.jpg',
      'https://project.supabase.co/storage/v1/object/public/avatars/user-1/other.jpg',
    ]) {
      expect(
        ownedProfileAvatarStoragePath(
          avatarUrl: url,
          userId: userId,
          expectedLegacyUrl: legacyUrl,
        ),
        isNull,
      );
    }
  });

  test('recognizes URLs generated by the configured avatar storage client', () {
    final avatars = SupabaseClient(
      'https://project.supabase.co',
      'test-anon-key',
    ).storage.from('avatars');

    expect(
      ownedProfileAvatarStoragePath(
        avatarUrl: avatars.getPublicUrl('user-1/avatar-123.jpg'),
        userId: userId,
        expectedLegacyUrl: avatars.getPublicUrl('user-1/avatar.jpg'),
      ),
      'user-1/avatar-123.jpg',
    );
  });
}
